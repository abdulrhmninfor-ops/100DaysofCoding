public class day27 {
    
    public static void main(String[] args) {
        
        int angka = 8; // Nilai awal variabel angka

        System.out.println("Nilai awal = " + angka);

        angka++; // Menambah nilai angka sebanyak 1
        System.out.println("Setelah increment = " + angka);

        angka--; // Mengurangi nilai angka sebanyak 1
        System.out.println("Setelah decrement = " + angka);
        
        
        
        
        
        
        
    }
    
}
