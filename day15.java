// Operator aritmatika perkalian (*) dan pembagian (/)
public class Day15 {
    
    public static void main(String[] args) {
        
        int a = 50;
        int b = 5;
        
        // menghitung perkalian
        int hasilPerkalian = a*b;
        // menghitung pembagian
        int hasilPembagian = a/b;
        
        
        // menampilkan hasil
        System.out.println("========== Day 15 ===========");
        System.out.println("Perkalian \t: " + hasilPerkalian);
        System.out.println("Pembagian \t: " + hasilPembagian);
        System.out.println("=============================");
        
        
        
        
    }
    
}
